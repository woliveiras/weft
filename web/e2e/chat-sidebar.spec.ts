import {expect,test} from '@playwright/test';

test('reads the full recent title with a mouse, keyboard and narrow touch search', async ({page,request,browser})=>{
  const headers={Authorization:'Bearer e2e-admin-token'};
  const settings=await(await request.get('/api/v1/chat/settings',{headers})).json();
  expect((await request.put('/api/v1/chat/settings',{headers:{...headers,'If-Match':String(settings.revision)},data:{provider:'e2e',name:'fixture'}})).ok()).toBe(true);
  const input={requestId:'ab0638046ab84b14a571c6fe2116b397',text:'Open the session detail fixture.'};
  const saved=await request.post('/api/v1/chat/sessions',{headers,data:input});
  expect(saved.ok()).toBe(true);
  const {title}=await saved.json();
  expect(title.length).toBeGreaterThan(90);
  await page.addInitScript(()=>localStorage.setItem('weftToken','e2e-admin-token'));
  await page.goto('/');
  const row=page.getByRole('listitem').filter({has:page.getByRole('button',{name:title,exact:true})});
  const opener=row.getByRole('button',{name:title,exact:true});
  expect(await opener.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
  await opener.hover();
  const preview=row.locator('.chat-session-preview');
  await expect(preview).toHaveText(new RegExp(title));
  expect(await preview.evaluate(card => {
    const rect = card.getBoundingClientRect();
    return card.contains(document.elementFromPoint(rect.left + rect.width / 2,rect.top + rect.height / 2));
  })).toBe(true);
  await preview.hover();
  await expect(preview).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(preview).toHaveCount(0);
  await page.mouse.move(0,0);
  await row.getByRole('button',{name:'Actions for '+title}).focus();
  await page.keyboard.press('Shift+Tab');
  await expect(opener).toBeFocused();
  await expect(preview).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(preview).toHaveCount(0);
  const message=page.getByRole('textbox',{name:'Message'});
  await message.fill('Keep my other conversation draft');
  await row.getByRole('button',{name:'Actions for '+title}).click();
  await row.getByRole('button',{name:'Rename'}).click();
  const rename=page.getByRole('dialog',{name:'Rename conversation'});
  const titleField=rename.getByRole('textbox',{name:'Conversation title'});
  const save=rename.getByRole('button',{name:'Save',exact:true});
  await titleField.fill('Renamed release session');
  const fieldBox=await titleField.boundingBox();
  const saveBox=await save.boundingBox();
  expect(saveBox!.y-(fieldBox!.y+fieldBox!.height)).toBeGreaterThanOrEqual(16);
  await save.click();
  await expect(page.getByRole('button',{name:'Renamed release session',exact:true})).toBeVisible();
  await expect(message).toHaveValue('Keep my other conversation draft');
  const renamed=page.getByRole('button',{name:'Actions for Renamed release session'});
  await renamed.click();
  await page.getByRole('button',{name:'Archive',exact:true}).click();
  await page.getByRole('button',{name:/^Archived/}).click();
  await expect(message).toHaveValue('Keep my other conversation draft');
  await renamed.click();
  await page.getByRole('button',{name:'Unarchive',exact:true}).click();
  await expect(renamed).toHaveCount(0);
  const mobile=await browser.newContext({baseURL:new URL(page.url()).origin,viewport:{width:375,height:800},hasTouch:true,reducedMotion:'reduce'});
  try{
    await mobile.addInitScript(()=>localStorage.setItem('weftToken','e2e-admin-token'));
    const phone=await mobile.newPage();
    await phone.goto('/');
    const search=phone.getByRole('button',{name:'Search conversations'});
    await search.tap();
    const dialog=phone.getByRole('dialog',{name:'Search conversations'});
    const query=dialog.getByRole('searchbox',{name:'Session title'});
    await expect(query).toBeFocused();
    await query.fill('missing title fixture');
    await expect(dialog.getByText('No matching conversations.')).toBeVisible();
    await query.fill('Renamed release');
    await expect(dialog.getByRole('button',{name:'Renamed release session'})).toBeVisible();
    await query.press('Escape');
    await expect(search).toBeFocused();
    await search.tap();
    await dialog.getByRole('button',{name:'Renamed release session'}).tap();
    await expect(phone.getByRole('heading',{name:'Renamed release session'})).toBeVisible();
    expect(await phone.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  } finally {await mobile.close();}
});
