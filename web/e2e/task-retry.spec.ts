import {test, expect} from '@playwright/test';

const headers={Authorization:'Bearer e2e-admin-token'};

test('creates a reviewed linked draft from a failed manual task without replaying its execution',async({page})=>{
 const graphId='manual-retry-flow';
 const graph={metadata:{id:graphId,name:'Manual retry flow'},spec:{nodes:[{id:'worker',runtime:{kind:'echo'},loop:{mode:'event'}}],channels:[{id:'requests',to:['worker'],approval:true,types:['feature.request']}]}};
 expect((await page.request.post('/api/v1/graphs',{headers,data:graph})).status()).toBe(201);
 const input={title:'Retry my manual task',request:'Preserve the reviewed request',outcome:'freeform',graphId,graphVersion:1,nodeId:'worker',resultNodeId:'worker',channelId:'requests',messageType:'feature.request',payloadJson:'{"message":"Preserve this payload"}'};
 const created=await page.request.post('/api/v1/tasks',{headers,data:input});
 expect(created.status()).toBe(201);const draft=await created.json();
 expect((await page.request.post(`/api/v1/tasks/${draft.id}/start`,{headers:{...headers,'If-Match':String(draft.revision)},data:{confirm:true}})).status()).toBe(202);
 await page.addInitScript(()=>localStorage.setItem('weftToken','e2e-admin-token'));
 await page.goto(`/#/tasks/${draft.id}`);
 await page.getByRole('region',{name:'Task decisions',exact:true}).getByRole('button',{name:'Reject',exact:true}).click();
 await expect(page.getByRole('region',{name:'Task status',exact:true})).toContainText('Task status: failed');
 await expect.poll(async()=>(await(await page.request.get(`/api/v1/tasks/${draft.id}`,{headers})).json()).status).toBe('failed');
 const original=await(await page.request.get(`/api/v1/tasks/${draft.id}`,{headers})).json();
 const originalExecutions=await(await page.request.get(`/api/v1/graphs/${original.executionGraphId}/executions`,{headers})).json();
 await page.setViewportSize({width:720,height:900});
 const retry=page.getByRole('region',{name:'Try task again'});
 await expect(retry).toContainText('new workspace and its own approvals');
 await page.screenshot({path:'test-results/task-retry-failed-narrow.png',fullPage:true});
 await retry.getByRole('button',{name:'Try again',exact:true}).focus();
 await page.keyboard.press('Enter');
 await expect(page).toHaveURL(new RegExp('#/tasks/tsk_'));
 await expect(page.getByRole('heading',{name:'Task draft',exact:true})).toBeVisible();
 await expect(page.getByRole('complementary',{name:'Attempt origin'})).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 const newID=page.url().split('/').pop()!;
 expect(newID).not.toBe(draft.id);
 const child=await(await page.request.get(`/api/v1/tasks/${newID}`,{headers})).json();
 expect(child).toMatchObject({...input,status:'draft',retryOfTaskId:draft.id,retryOfRevision:original.revision});
 expect(child.executionGraphId).toBeUndefined();expect(child.submitted).toBeUndefined();expect(child.environmentApprovalId).toBeUndefined();
 await expect(page.getByRole('link',{name:'Original failed task'})).toHaveAttribute('href',`#/tasks/${draft.id}`);
 await page.screenshot({path:'test-results/task-retry-draft-narrow.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'test-results/task-retry-draft-wide.png',fullPage:true});
 await page.reload();
 await expect(page.getByRole('link',{name:'Original failed task'})).toBeVisible();
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue(input.request);
 await expect(page.getByRole('combobox',{name:'Workflow version',exact:true})).toHaveValue('1');
 await page.getByRole('button',{name:'Review task',exact:true}).click();
 await expect(page.getByRole('article',{name:'Task requirements',exact:true})).toBeVisible();
 const requirements=await(await page.request.get(`/api/v1/tasks/${newID}/review`,{headers})).json();
 expect(requirements.canStart).toBe(true);
 expect(requirements.validation.errors??[]).toEqual([]);
 expect(requirements.executionGraphId).toMatch(/^task-run-h-[a-z2-7]{52}$/);
 expect(requirements.executionGraphId.length).toBe(63);
 const reviewed=await(await page.request.get(`/api/v1/tasks/${newID}`,{headers})).json();
 expect(reviewed.status).toBe('draft');expect(reviewed.executionGraphId).toBeUndefined();
 expect(await(await page.request.get(`/api/v1/tasks/${draft.id}`,{headers})).json()).toEqual(original);
 expect(await(await page.request.get(`/api/v1/graphs/${original.executionGraphId}/executions`,{headers})).json()).toEqual(originalExecutions);
 expect(await(await page.request.get(`/api/v1/graphs/${graphId}/executions`,{headers})).json()).toEqual([]);
 await page.getByRole('link',{name:'Original failed task'}).click();
 await expect(page.getByRole('region',{name:'Task status',exact:true})).toContainText('Task status: failed');
 await page.getByRole('button',{name:'Try again',exact:true}).click();
 await expect(page).toHaveURL(new RegExp(`#/tasks/${newID}$`));
 // An explicit new start must pass admission and keep evidence linked to the long task ID.
 await page.getByRole('button',{name:'Review task',exact:true}).click();
 const ready=page.getByRole('article',{name:'Task requirements',exact:true});
 await ready.getByRole('checkbox',{name:'I reviewed the workflow and authorize a separate execution copy.'}).check();
 await ready.getByRole('button',{name:'Start task',exact:true}).click();
 await expect(page.getByRole('region',{name:'Task decisions',exact:true})).toBeVisible();
 const started=await(await page.request.get(`/api/v1/tasks/${newID}`,{headers})).json();
 expect(started.executionGraphId).toBe(requirements.executionGraphId);
 await page.goto(`/#/g/${started.executionGraphId}/runs`);
 await expect(page.getByRole('heading',{name:'Task execution',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Back to task',exact:true})).toHaveAttribute('href',`#/tasks/${newID}`);
 await expect(page.getByText('No executions recorded yet.',{exact:true})).toBeVisible();
});
