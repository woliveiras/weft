import { test, expect } from '@playwright/test';
const headers={Authorization:'Bearer e2e-admin-token'};
const cloudId='11111111-2222-3333-4444-555555555555';
test('configures separate Jira REST access through the console and real API without contacting Atlassian',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('weftToken','e2e-admin-token'));
 await page.setViewportSize({width:1280,height:800});
 await page.goto('/#/connections/new');
 await page.getByLabel('Connection ID',{exact:true}).fill('jira-rest-browser');
 await page.getByLabel('Connection name',{exact:true}).fill('Jira REST browser fixture');
 await page.getByLabel('Service',{exact:true}).selectOption('atlassian');
 await page.getByLabel('MCP endpoint',{exact:true}).fill('https://mcp.atlassian.com/v2/mcp?tools=all');
 await page.getByLabel('Bearer token',{exact:true}).fill('synthetic-mcp-browser-token');
 await page.getByRole('checkbox',{name:'Configure separate Jira REST access',exact:true}).check();
 await page.getByLabel('Jira Cloud ID',{exact:true}).fill(cloudId);
 await page.getByLabel('Jira REST API token owner email',{exact:true}).fill('robot@example.test');
 await page.getByLabel('Jira REST API token',{exact:true}).fill('synthetic-rest-browser-token');
 await page.getByRole('checkbox',{name:'Connection enabled',exact:true}).uncheck();
 const save=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/v1/mcp/connections'));
 await page.getByRole('button',{name:'Save MCP connection',exact:true}).click();
 expect((await save).status()).toBe(201);
 await expect(page).toHaveURL(/connections\/c\/jira-rest-browser\/overview$/);
 await expect(page.getByRole('region',{name:'Jira REST access status'})).toContainText('REST credential configured');
 const saved=await page.request.get('/api/v1/mcp/connections/jira-rest-browser',{headers});
 expect(saved.status()).toBe(200);
 const savedBody=await saved.text();
 expect(savedBody).not.toContain('synthetic-mcp-browser-token');
 expect(savedBody).not.toContain('synthetic-rest-browser-token');
 expect(savedBody).not.toContain('robot@example.test');
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Edit Jira REST browser fixture',exact:true}).click();
 await expect(page.getByLabel('Jira Cloud ID',{exact:true})).toHaveValue(cloudId);
 await expect(page.getByLabel('Jira REST API token owner email',{exact:true})).toHaveValue('');
 await expect(page.getByLabel('Jira REST API token',{exact:true})).toHaveValue('');
 await page.getByRole('region',{name:'Separate Jira Cloud REST access',exact:true}).screenshot({path:test.info().outputPath('jira-rest-desktop.png')});
 await page.getByLabel('Service',{exact:true}).selectOption('github');
 await expect(page.getByRole('alert')).toContainText('stored configuration has not been removed');
 await expect(page.getByLabel('Jira Cloud ID',{exact:true})).toHaveValue(cloudId);
 await page.getByLabel('Service',{exact:true}).selectOption('atlassian');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
 await page.getByRole('region',{name:'Separate Jira Cloud REST access',exact:true}).screenshot({path:test.info().outputPath('jira-rest-mobile.png')});
 await page.getByRole('button',{name:'Help for Jira REST API token',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('MCP agent-interface scopes are insufficient');
 await page.keyboard.press('Escape');
 await page.getByRole('checkbox',{name:'Clear stored Jira REST credential',exact:true}).check();
 await page.getByRole('button',{name:'Save MCP connection',exact:true}).click();
 await expect(page).toHaveURL(/connections\/c\/jira-rest-browser\/overview$/);
 await expect(page.getByRole('region',{name:'Jira REST access status'})).toContainText('REST credential missing');
 const cleared=await page.request.get('/api/v1/mcp/connections/jira-rest-browser',{headers});
 expect(await cleared.json()).toMatchObject({credentialConfigured:true,jiraRest:{cloudId,credentialConfigured:false}});
});
