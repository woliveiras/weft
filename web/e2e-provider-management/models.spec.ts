import {expect,test} from '@playwright/test';

test('separates model configuration destinations and opens creation as a full page',async({page})=>{
  await page.addInitScript(()=>{if(!localStorage.getItem('weftToken'))localStorage.setItem('weftToken','e2e-admin-token');});
  await page.goto('/#/models/plugins');
  const plugin=page.getByRole('listitem',{name:'Inference plugin OpenAI',exact:true});
  await expect(plugin).toBeVisible();
  if(await plugin.getByRole('button',{name:'Enable',exact:true}).isVisible())await plugin.getByRole('button',{name:'Enable',exact:true}).click();
  await expect(plugin.getByText('Enabled',{exact:true})).toBeVisible();
  const seed=await page.request.post('/api/v1/providers',{headers:{Authorization:'Bearer e2e-admin-token'},data:{name:'navigation-provider',type:'openai',defaultModel:'fixture',apiKey:{value:'synthetic-navigation-key'}}});
  expect(seed.ok()).toBeTruthy();
  await page.getByRole('link',{name:'Providers',exact:true}).click();
  const sections=page.getByRole('navigation',{name:'Model settings sections'});
  await expect(sections.getByRole('link',{name:'Providers',exact:true})).toHaveAttribute('aria-current','page');
  await page.getByRole('button',{name:'Refresh providers',exact:true}).click();
  await expect(page.getByRole('article').first()).toBeVisible();
  await expect(page.getByRole('group',{name:'Inference plugins',exact:true})).toHaveCount(0);
  await page.getByLabel('Search providers').fill('no matching provider');
  await expect(page.getByText('No providers match these filters.')).toBeVisible();
  await page.getByRole('button',{name:'Clear filters'}).click();
  await page.getByRole('button',{name:'Add provider',exact:true}).click();
  await expect(page).toHaveURL(/#\/models\/providers\/new$/);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const form=page.getByRole('form',{name:'Provider settings'});
  await expect(form.getByLabel('Name',{exact:true})).toBeFocused();
  await form.getByLabel('Name',{exact:true}).fill('unsaved-provider');
  await form.getByText('Limits',{exact:true}).click();
  await expect(form.getByLabel('Context window (tokens)',{exact:true})).toBeVisible();
  const context=await form.getByLabel('Context window (tokens)',{exact:true}).boundingBox();
  const timeout=await form.getByLabel('Timeout (seconds)',{exact:true}).boundingBox();
  expect(Math.abs(context!.height-timeout!.height)).toBeLessThan(2);
  await page.getByRole('button',{name:'Back to providers'}).click();
  await expect(page).toHaveURL(/#\/models$/);
  await sections.getByRole('link',{name:'Inference plugins',exact:true}).click();
  await expect(page.getByRole('listitem',{name:/Inference plugin/}).first()).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(0);
  await sections.getByRole('link',{name:'Usage & costs',exact:true}).click();
  await expect(page.getByRole('group',{name:/Spend in/})).toBeVisible();
  await expect(page.getByRole('form',{name:'Model prices'})).toHaveCount(0);
  await sections.getByRole('link',{name:'Budgets',exact:true}).click();
  await expect(page.getByRole('form',{name:'Default budget per task'})).toBeVisible();
  await sections.getByRole('link',{name:'Model prices',exact:true}).click();
  await expect(page.getByRole('form',{name:'Model prices'})).toBeVisible();
  await page.reload(); await expect(sections.getByRole('link',{name:'Model prices',exact:true})).toHaveAttribute('aria-current','page');
  await page.goBack(); await expect(sections.getByRole('link',{name:'Budgets',exact:true})).toHaveAttribute('aria-current','page');
});

test('keeps provider forms aligned on a narrow viewport and rejects viewer edit routes',async({page})=>{
  await page.setViewportSize({width:580,height:850});
  await page.addInitScript(()=>{if(!localStorage.getItem('weftToken'))localStorage.setItem('weftToken','e2e-admin-token');});
  await page.goto('/#/models/providers/new');
  const form=page.getByRole('form',{name:'Provider settings'});
  await expect(form).toBeVisible();
  await form.getByText('Limits',{exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const details=await form.getByRole('region',{name:'Provider details'}).boundingBox();
  const authentication=await form.getByRole('region',{name:'Authentication'}).boundingBox();
  expect(authentication!.y).toBeGreaterThan(details!.y+details!.height);
  await form.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.evaluate(()=>localStorage.setItem('weftToken','e2e-viewer-token'));
  await page.goto('/#/models/providers/missing/edit'); await page.reload();
  await expect(page.getByText('Only an administrator can configure model providers.')).toBeVisible();
  await expect(page.getByRole('form',{name:'Provider settings'})).toHaveCount(0);
  const denied=await page.request.post('/api/v1/providers',{headers:{Authorization:'Bearer e2e-viewer-token'},data:{name:'denied',type:'mock'}});
  expect(denied.status()).toBe(403);
});
